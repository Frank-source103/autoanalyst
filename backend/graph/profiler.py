"""Trusted data profiling script generator for AutoAnalyst."""

PROFILING_SCRIPT = """
import os
import glob
import json
import pandas as pd
import numpy as np

def run_profiling():
    files = glob.glob('/data/input.*')
    if not files:
        print(json.dumps({'error': 'No input dataset found at /data/input.*'}))
        return

    filepath = files[0]
    ext = os.path.splitext(filepath)[1].lower()

    try:
        if ext == '.csv':
            # Try reading with comma, fallback to auto delimiter
            try:
                df = pd.read_csv(filepath, nrows=10000)
            except Exception:
                df = pd.read_csv(filepath, sep=None, engine='python', nrows=10000)
        elif ext == '.parquet':
            df = pd.read_parquet(filepath)
        else:
            print(json.dumps({'error': f'Unsupported dataset format: {ext}'}))
            return

        total_rows = len(df)
        total_cols = len(df.columns)

        columns_meta = []
        dtypes_dict = {}

        for col in df.columns:
            series = df[col]
            dtype_str = str(series.dtype)
            dtypes_dict[col] = dtype_str
            null_count = int(series.isnull().sum())
            null_rate = round(null_count / total_rows, 4) if total_rows > 0 else 0.0

            col_info = {
                'name': col,
                'dtype': dtype_str,
                'null_count': null_count,
                'null_rate': null_rate,
                'unique_count': int(series.nunique(dropna=True))
            }

            if pd.api.types.is_numeric_dtype(series):
                desc = series.describe()
                col_info['numeric_stats'] = {
                    'min': float(desc.get('min', 0.0)) if pd.notnull(desc.get('min')) else None,
                    'max': float(desc.get('max', 0.0)) if pd.notnull(desc.get('max')) else None,
                    'mean': float(desc.get('mean', 0.0)) if pd.notnull(desc.get('mean')) else None,
                    'std': float(desc.get('std', 0.0)) if pd.notnull(desc.get('std')) else None,
                }
            else:
                # Top frequent values
                val_counts = series.value_counts().head(5).to_dict()
                col_info['top_values'] = {str(k): int(v) for k, v in val_counts.items()}

            columns_meta.append(col_info)

        # Sample rows (first 5) sanitized of NaN
        sample_rows = df.head(5).replace({np.nan: None}).to_dict(orient='records')

        profile_data = {
            'row_count': total_rows,
            'column_count': total_cols,
            'columns': [str(c) for c in df.columns],
            'dtypes': dtypes_dict,
            'column_details': columns_meta,
            'sample_rows': sample_rows
        }

        # Save to /tmp/output/profile.json and print marker
        os.makedirs('/tmp/output', exist_ok=True)
        with open('/tmp/output/profile.json', 'w', encoding='utf-8') as f:
            json.dump(profile_data, f)

        print("__PROFILE_OUTPUT_START__")
        print(json.dumps(profile_data))
        print("__PROFILE_OUTPUT_END__")

    except Exception as e:
        print(json.dumps({'error': f'Failed profiling dataset: {str(e)}'}))

if __name__ == '__main__':
    run_profiling()
"""


def get_trusted_profiling_code() -> str:
    """Return the fixed, trusted profiling Python script. Never generated by an LLM."""
    return PROFILING_SCRIPT.strip()
